// Aritméticos: + - * / %
// Lógicos e Binários: && || ! & ^
// Relacionais: >= == != <= > <
// Concatenação: + ${}
// Decisão: ?:

// Exemplos:
let b1 = z > c && c <= d;
let texto = z >= 5 ? 'APR' : 'RPR';
let k = 5 ^ 2; // 0101 xor 0010 -> 0111(7)

let x = 1 + 2;
x *= 3; // Valor final de x será 9
let f1 = 'Valor de x: ' + x;
let f2 = 'Valor de x: ' + x;
let f3 = `Valor de x: ${x}`;
